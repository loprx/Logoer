#!/bin/bash
#
# Build Logoer with the Command Line Tools only — no Xcode.app required.
#
#   ./scripts/build.sh                 # build to build/Logoer.app
#   ./scripts/build.sh --install       # ...and replace /Applications/Logoer.app
#   CODESIGN_IDENTITY="Developer ID Application: …" ./scripts/build.sh
#
# SwiftPM compiles the sources; this script assembles the .app bundle by hand
# because `actool` (Assets.car) and `ibtool` (storyboards) only ship with Xcode:
#
#   * Assets.xcassets is flattened into loose files in Contents/Resources and the
#     app resolves artwork with logoImage()/logoColor(), which accept both an
#     asset catalog and loose resources. AppIcon.appiconset becomes AppIcon.icns
#     via iconutil.
#   * LogoerHelper is compiled without its storyboard (the storyboard is just an
#     empty menu bar; the helper only needs its delegate).
#
# Caveat: without a Developer ID the bundle is ad-hoc signed. Everything works
# locally, but Sparkle cannot install updates into an ad-hoc signed app.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APP_NAME="Logoer"
CONFIG=release
OUT="$ROOT/build/$APP_NAME.app"
# Version comes from the Xcode project so the two build paths cannot drift.
VERSION="$(sed -n 's/.*MARKETING_VERSION = \(.*\);/\1/p' "$ROOT/Logoer.xcodeproj/project.pbxproj" | head -1)"
BUILD_NUMBER="$(sed -n 's/.*CURRENT_PROJECT_VERSION = \(.*\);/\1/p' "$ROOT/Logoer.xcodeproj/project.pbxproj" | head -1)"
BUNDLE_ID="com.lihaoyun6.Logoer"
HELPER_ID="com.lihaoyun6.LogoerHelper"
MIN_MACOS="11.0"
CODESIGN_IDENTITY="${CODESIGN_IDENTITY:--}"

[ -n "$VERSION" ] && [ -n "$BUILD_NUMBER" ] || {
    echo "could not read MARKETING_VERSION / CURRENT_PROJECT_VERSION from project.pbxproj" >&2
    exit 1
}

info() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }

# ---------------------------------------------------------------- compile ----
info "swift build -c $CONFIG"
cd "$ROOT"
swift build -c "$CONFIG" --product "$APP_NAME"
BIN_DIR="$(swift build -c "$CONFIG" --show-bin-path)"

# ------------------------------------------------------------- app bundle ----
info "assembling $OUT"
rm -rf "$OUT"
mkdir -p "$OUT/Contents/"{MacOS,Frameworks,Resources,Library/LoginItems}
cp "$BIN_DIR/$APP_NAME" "$OUT/Contents/MacOS/$APP_NAME"

# Sparkle is a binary framework from a SwiftPM artifact; point the loader at
# Contents/Frameworks (the SPM build only has @loader_path/..). Xcode does the
# same for embedded frameworks automatically.
cp -R "$BIN_DIR/Sparkle.framework" "$OUT/Contents/Frameworks/"
install_name_tool -add_rpath "@executable_path/../Frameworks" "$OUT/Contents/MacOS/$APP_NAME" 2>/dev/null || true

# Resource bundles generated by SwiftPM (privacy manifests). Upstream Xcode puts
# them in Contents/Resources. Copy regular files only: SwiftPM symlinks the
# manifest to a path inside .build, which is dangling once the build directory is
# cleaned, and a dangling symlink fails strict code-signing verification.
for bundle in "$BIN_DIR"/SDWebImage*.bundle; do
    [ -e "$bundle" ] || continue
    dest="$OUT/Contents/Resources/$(basename "$bundle")"
    mkdir -p "$dest"
    find "$bundle" -type f -exec cp {} "$dest/" \;
    [ -n "$(ls -A "$dest")" ] || rmdir "$dest"
done

# --- artwork: flatten Assets.xcassets (actool is Xcode-only) -----------------
info "flattening Assets.xcassets"
python3 - "$ROOT/Logoer/Assets.xcassets" "$OUT/Contents/Resources" <<'PY'
import json, os, shutil, sys

catalog, dest = sys.argv[1], sys.argv[2]
for entry in sorted(os.listdir(catalog)):
    path = os.path.join(catalog, entry)
    manifest = os.path.join(path, "Contents.json")
    if not os.path.isdir(path) or not os.path.isfile(manifest):
        continue
    if entry.endswith(".appiconset"):
        continue                      # handled by iconutil below
    if entry.endswith(".colorset"):
        continue                      # logoColor() has the values in code
    if not entry.endswith(".imageset"):
        continue
    with open(manifest) as f:
        images = json.load(f).get("images", [])
    for image in images:
        filename = image.get("filename")
        if not filename or image.get("scale") not in (None, "1x"):
            continue
        ext = os.path.splitext(filename)[1]
        # actool exposes the imageset name, without extension, to NSImage(named:)
        shutil.copyfile(os.path.join(path, filename),
                        os.path.join(dest, entry[:-len(".imageset")] + ext))
        break
PY

# --- app icon ---------------------------------------------------------------
ICONSET="$ROOT/Logoer/Assets.xcassets/AppIcon.appiconset"
if [ -d "$ICONSET" ] && command -v iconutil >/dev/null; then
    TMPICONSET="$(mktemp -d)/AppIcon.iconset"
    mkdir -p "$TMPICONSET"
    cp "$ICONSET"/icon_*.png "$TMPICONSET"/
    iconutil --convert icns --output "$OUT/Contents/Resources/AppIcon.icns" "$TMPICONSET"
    rm -rf "$(dirname "$TMPICONSET")"
fi

# --- other resources --------------------------------------------------------
cp "$ROOT/Logoer/Resources/"*.svg "$OUT/Contents/Resources/"
mkdir -p "$OUT/Contents/Resources/zh-Hans.lproj"
cp "$ROOT/Logoer/zh-Hans.lproj/Localizable.strings" "$OUT/Contents/Resources/zh-Hans.lproj/"

# --- Info.plist -------------------------------------------------------------
# Start from the checked-in plist (it carries SUFeedURL/SUPublicEDKey) and add
# what Xcode's GENERATE_INFOPLIST_FILE + build settings would have added.
cp "$ROOT/Logoer/Info.plist" "$OUT/Contents/Info.plist"
P=/usr/libexec/PlistBuddy
$P -c "Delete :CFBundleExecutable" "$OUT/Contents/Info.plist" 2>/dev/null || true
$P -c "Add :CFBundleExecutable string $APP_NAME" "$OUT/Contents/Info.plist"
$P -c "Add :CFBundleIdentifier string $BUNDLE_ID" "$OUT/Contents/Info.plist"
$P -c "Add :CFBundleName string $APP_NAME" "$OUT/Contents/Info.plist"
$P -c "Add :CFBundlePackageType string APPL" "$OUT/Contents/Info.plist"
$P -c "Add :CFBundleShortVersionString string $VERSION" "$OUT/Contents/Info.plist"
$P -c "Add :CFBundleVersion string $BUILD_NUMBER" "$OUT/Contents/Info.plist"
$P -c "Add :CFBundleIconFile string AppIcon" "$OUT/Contents/Info.plist"
$P -c "Add :CFBundleInfoDictionaryVersion string 6.0" "$OUT/Contents/Info.plist"
$P -c "Add :CFBundleDevelopmentRegion string en" "$OUT/Contents/Info.plist"
$P -c "Add :LSMinimumSystemVersion string $MIN_MACOS" "$OUT/Contents/Info.plist"
$P -c "Add :LSUIElement bool true" "$OUT/Contents/Info.plist"
$P -c "Add :NSHighResolutionCapable bool true" "$OUT/Contents/Info.plist"
$P -c "Add :NSHumanReadableCopyright string Copyright © 2024 lihaoyun6. Fork maintained at github.com/loprx/Logoer." \
    "$OUT/Contents/Info.plist"
printf 'APPL????' > "$OUT/Contents/PkgInfo"

# --- login-item helper ------------------------------------------------------
# The Xcode target is a storyboard app; the storyboard only contributes an empty
# menu bar, so compile the two Swift files directly and leave
# NSMainStoryboardFile out of the helper's Info.plist.
info "building LogoerHelper"
HELPER="$OUT/Contents/Library/LoginItems/LogoerHelper.app"
mkdir -p "$HELPER/Contents/MacOS"
HELPER_SOURCES=("$ROOT/LogoerHelper/main.swift" "$ROOT/LogoerHelper/LogoerHelper.swift")
CATALOG=$(xcrun --show-sdk-path)
swiftc -O -target "arm64-apple-macos$MIN_MACOS" -Xlinker -rpath -Xlinker @executable_path/../Frameworks \
    -o "$HELPER/Contents/MacOS/LogoerHelper" "${HELPER_SOURCES[@]}"
cat > "$HELPER/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
    <key>CFBundleDevelopmentRegion</key><string>en</string>
    <key>CFBundleExecutable</key><string>LogoerHelper</string>
    <key>CFBundleIdentifier</key><string>$HELPER_ID</string>
    <key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
    <key>CFBundleName</key><string>LogoerHelper</string>
    <key>CFBundlePackageType</key><string>APPL</string>
    <key>CFBundleShortVersionString</key><string>0.1.3</string>
    <key>CFBundleVersion</key><string>013</string>
    <key>LSBackgroundOnly</key><true/>
    <key>LSMinimumSystemVersion</key><string>$MIN_MACOS</string>
</dict></plist>
PLIST
printf 'APPL????' > "$HELPER/Contents/PkgInfo"

# ---------------------------------------------------------------- signing ----
# $(PRODUCT_BUNDLE_IDENTIFIER) is expanded by Xcode at build time; resolve it here.
ENTITLEMENTS="$(mktemp -t logoer-entitlements)"
sed "s/\$(PRODUCT_BUNDLE_IDENTIFIER)/$BUNDLE_ID/g" "$ROOT/Logoer/Logoer.entitlements" > "$ENTITLEMENTS"
HELPER_ENTITLEMENTS="$(mktemp -t logoer-helper-entitlements)"
cp "$ROOT/LogoerHelper/LogoerHelper.entitlements" "$HELPER_ENTITLEMENTS"

info "codesigning with identity '$CODESIGN_IDENTITY'"
# Ad-hoc signatures get a designated requirement built from the cdhash, and the cdhash
# changes on every rebuild. macOS stores that requirement in the TCC grant for Screen
# Recording, so each rebuild silently invalidates Auto-Mask's permission and the user has
# to toggle it again. Pin the app's requirement to its bundle identifier instead: that is
# the same for every build, so the grant survives. Only the app needs it — the nested
# helper and Sparkle framework have their own identifiers, and a requirement naming the
# app's identifier would not match them.
REQUIREMENT_ARGS=()
if [ "$CODESIGN_IDENTITY" = "-" ]; then
    echo "   (ad-hoc: Sparkle auto-update will not install into this build)"
    REQUIREMENT_ARGS=(-r="designated => identifier \"$BUNDLE_ID\"")
fi
codesign --force --sign "$CODESIGN_IDENTITY" --entitlements "$HELPER_ENTITLEMENTS" \
    --identifier "$HELPER_ID" "$HELPER"
codesign --force --deep --sign "$CODESIGN_IDENTITY" "$OUT/Contents/Frameworks/Sparkle.framework"
codesign --force --deep --sign "$CODESIGN_IDENTITY" --entitlements "$ENTITLEMENTS" \
    --identifier "$BUNDLE_ID" ${REQUIREMENT_ARGS[@]+"${REQUIREMENT_ARGS[@]}"} "$OUT"
rm -f "$ENTITLEMENTS" "$HELPER_ENTITLEMENTS"

codesign --verify --deep --strict --verbose=1 "$OUT" 2>&1 | tail -3

if [ "${1:-}" = "--install" ]; then
    info "installing to /Applications/$APP_NAME.app"
    osascript -e "tell application id \"$BUNDLE_ID\" to quit" 2>/dev/null || true
    sleep 1
    rm -rf "/Applications/$APP_NAME.app"
    cp -R "$OUT" "/Applications/$APP_NAME.app"
    open "/Applications/$APP_NAME.app"
fi

info "done: $OUT"
